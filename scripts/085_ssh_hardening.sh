connect_help() {
    clear
    echo -e "${BOLD}${CYAN}  Connect to this server with your private key${RESET}"
    echo ""

    local port ip
    port="$(_ssh_port)"
    # Public IP this session came in on, falling back to a best-effort lookup.
    ip="$(awk '{print $3}' <<<"${SSH_CONNECTION:-}")"
    [[ -z "$ip" ]] && ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
    [[ -z "$ip" ]] && ip="<server-ip>"

    # Once the guided setup has run, root cannot log in at all — printing
    # root@ here would hand the operator a line that is guaranteed to fail.
    local login="root" rl
    rl="$(_ssh_effective permitrootlogin)"
