# =============================================================================
# 07_lib_pool_dbsnap.sh — frequent DB snapshots for the PUBLIC POOL hub
# =============================================================================
# The daily full archive (07_lib_pool_backup.sh) carries everything a fresh install
# cannot regenerate, the wallet seed included. Only the databases change quickly, so on
# a busy pool a day-old archive can lose up to a day of share credit. A snapshot holds
# ONLY pool.db and the games DB, taken every 15 / 30 / 60 / 120 min:
#
#   Name     : /opt/grin/backups/grin_<product>_dbsnap_<DDMMYYYY>_<HHMM>.tar.gz.enc
#              ("_dbsnap_", never "_backup_": no daily-archive glob, restore list, Migrate
#              IN or remote day-prune matches it)
#   Password : <personal_key><DDMMYYYY> — the same rule as every other archive. Date and
#              time in a snapshot name are UTC (local time repeats an hour at DST fall-back).
#   Contents : pool.db (+ games DB when /play/ is installed), SQLite backup API only.
#              No seed, config, WG key or vhost: those stay in the daily archive, so
#              24 snapshots a day do not mean 24 offsite copies of the seed.
#   Runs     : $PBK_WRAPPER dbsnap from $PDS_CRON (at :02/:17/:32/:47 — never on the
#              hour, where the daily run and other crons sit). The wrapper skips a run
#              when the databases have not changed, or when another pool backup holds
#              $PBK_LOCK. Retention: newest $PDS_KEEP locally; offsite via the shared push
#              (its own hour-based remote retention, grin_backup_push.sh).
#
# Restore order on a FRESH box: the newest daily archive first (2 → full), then the newest
# snapshot on top (2 → DB snapshot). On an intact box a snapshot restore stands alone.
# Either way the restored ledger comes up with payouts FROZEN and stratum PAUSED — the
# same restore core as the full restore (_pbk_restore_extract).
#
# Sourced at the end of 07_lib_pool_backup.sh (reuses PBK_*/PDS_*, pbk_* and the restore
# core). Convention: sourced lib → NO shebang / NO `set -e`; every create/move/delete is
# guarded on its own (callers run it under `|| true`, which disables errexit here).
# =============================================================================

[[ -n "${_GRIN_POOL_DBSNAP_SH_LOADED:-}" ]] && return 0
_GRIN_POOL_DBSNAP_SH_LOADED=1

# ─── Cron ────────────────────────────────────────────────────────────────────
# Minute fields for each interval. Offset from :00 so a snapshot never starts with the
# daily run (02:00 by default) or the many hourly jobs that fire on the hour.
_pds_cron_spec() {
    case "$1" in
        15)  echo "2,17,32,47 * * * *" ;;
        30)  echo "17,47 * * * *" ;;
        120) echo "17 */2 * * *" ;;
        *)   echo "17 * * * *" ;;
    esac
}

pds_enabled() { [[ -f "$PDS_CRON" ]]; }

# Writes the wrapper and the cron file. The cron file goes in by rename: cron ignores
# names with a dot, so the half-written "$PDS_CRON.new" is never read.
_pds_install_cron() {
    _pbk_write_wrapper || return 1
    printf '# Grin public pool hub DB snapshot — generated by 07_grin_mining_public_pool.sh\n%s root %s dbsnap\n' \
        "$(_pds_cron_spec "$PDS_INTERVAL")" "$PBK_WRAPPER" > "$PDS_CRON.new" \
        && chmod 644 "$PDS_CRON.new" && mv -f "$PDS_CRON.new" "$PDS_CRON" \
        || { rm -f "$PDS_CRON.new" 2>/dev/null; error "Could not write $PDS_CRON."; return 1; }
}

# Removes the snapshot cron. The wrapper stays while the daily cron still uses it.
pds_disable() {
    rm -f "$PDS_CRON" || { error "Could not remove $PDS_CRON."; return 1; }
    if [[ ! -f "$PBK_CRON" ]]; then rm -f "$PBK_WRAPPER" 2>/dev/null || true; fi
    return 0
}

pds_enable() {
    gbe_require_key || { info "Scheduling needs a personal key."; return 1; }
    command -v python3 >/dev/null 2>&1 || { error "python3 not found — the snapshot needs the SQLite backup API."; return 1; }
    command -v flock >/dev/null 2>&1   || { error "flock not found (util-linux) — cannot schedule safely."; return 1; }
    pbk_save_conf || return 1
    _pds_install_cron || return 1
    success "DB snapshot enabled → $PDS_CRON  (every $PDS_INTERVAL min, keep $PDS_KEEP)"
}

# ─── Regenerate everything the pool box runs from a generated copy ──────────
# Called by pool deploy (key 9), games install, and the schedule screens. Rewrites
# only what is installed: the wrapper when either cron exists, the snapshot cron line
# (its interval), and the shared push commands.
pool_backup_refresh_generated() {
    local rc=0
    pbk_load_conf
    if [[ -f "$PBK_CRON" || -f "$PDS_CRON" ]]; then
        _pbk_write_wrapper || rc=1
        if ! command -v flock >/dev/null 2>&1; then
            warn "flock (util-linux) is missing — scheduled pool backups cannot take their lock and will fail."
            rc=1
        fi
    fi
    if [[ -f "$PDS_CRON" ]]; then _pds_install_cron || rc=1; fi
    gbp_refresh_installed || rc=1
    return "$rc"
}

# ─── Listing ─────────────────────────────────────────────────────────────────
pds_list() {
    echo ""
    echo -e "  ${BOLD}DB snapshots in $PBK_BACKUP_DIR:${RESET}"
    local any=0 f sz n=0
    while IFS= read -r f; do
        [[ -n "$f" ]] || continue
        any=1; n=$((n + 1))
        if [[ "$n" -le 8 ]]; then
            sz=$(du -sh "$f" 2>/dev/null | cut -f1 || echo "?")
            echo -e "    $(basename "$f")  ${DIM}($sz)${RESET}"
        fi
    done < <(ls -t "$PBK_BACKUP_DIR/${PDS_PREFIX}"*.tar.gz.enc 2>/dev/null || true)
    if [[ "$n" -gt 8 ]]; then echo -e "    ${DIM}… and $((n - 8)) older${RESET}"; fi
    if [[ "$any" -eq 0 ]]; then echo -e "    ${DIM}(none yet)${RESET}"; fi
}

# Last wrapper log line for snapshots (or empty).
_pds_last_log() {
    grep -F "dbsnap:" "$PBK_LOG" 2>/dev/null | tail -1
}

# DDMMYYYY of a snapshot name, rc 1 if it is not one of ours. The date is NOT the last
# field here (HHMM is), so gbe_parse_date cannot read it.
pds_parse_date() {
    local base; base=$(basename "$1")
    if [[ "$base" =~ ^${PDS_PREFIX}([0-9]{8})_[0-9]{4}\.tar\.gz\.enc$ ]]; then
        echo "${BASH_REMATCH[1]}"; return 0
    fi
    return 1
}

# ─── Schedules screen (pool Backup & Restore → 3) ────────────────────────────
pds_schedule_menu() {
    local c n
    while true; do
        clear
        pbk_load_conf
        echo -e "${BOLD}${CYAN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
        echo -e "${BOLD}${CYAN}  Pool hub — Backup schedules (${POOL_NET_LABEL:-$POOL_NET})${RESET}"
        echo -e "${BOLD}${CYAN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
        echo ""
        local daily="${RED}off${RESET}" snap="${RED}off${RESET}" push
        [[ -f "$PBK_CRON" ]] && daily="${GREEN}on${RESET} ${DIM}($(printf '%02d:%02d' "$PBK_HOUR" "$PBK_MIN") UTC, keep $PBK_KEEP)${RESET}"
        pds_enabled && snap="${GREEN}on${RESET} ${DIM}(every $PDS_INTERVAL min, keep $PDS_KEEP)${RESET}"
        if [[ "$PDS_PUSH" != 1 ]]; then push="off — snapshots stay on this box"
        elif [[ "$PDS_PUSH_MIN" -gt 0 ]]; then push="at most every $PDS_PUSH_MIN min"
        else push="every snapshot"; fi
        if ! gbp_configured; then push+=" ${DIM}(offsite push not configured — key 5 on the previous screen)${RESET}"; fi
        echo -e "  Daily full archive : $daily"
        echo -e "  DB snapshot        : $snap"
        echo -e "  Snapshot offsite   : $push"
        local last; last=$(_pds_last_log)
        [[ -n "$last" ]] && echo -e "  Last snapshot run  : ${DIM}$last${RESET}"
        echo ""
        echo -e "  ${DIM}Daily = everything incl. the wallet seed. Snapshot = pool.db + games DB only,${RESET}"
        echo -e "  ${DIM}so a busy pool loses at most one interval of share credit, not a day.${RESET}"
        echo ""
        echo -e "  ${GREEN}1${RESET}) Daily full archive on/off"
        echo -e "  ${GREEN}2${RESET}) DB snapshot on/off"
        echo -e "  ${GREEN}3${RESET}) Snapshot interval        ${DIM}(15 / 30 / 60 / 120 min)${RESET}"
        echo -e "  ${GREEN}4${RESET}) Snapshot retention       ${DIM}(how many to keep on this box)${RESET}"
        echo -e "  ${GREEN}5${RESET}) Snapshot offsite push    ${DIM}(every one / at most every N min / off)${RESET}"
        echo -e "  ${RED}0${RESET}) Back"
        echo ""
        echo -ne "${BOLD}Select [1-5/0]: ${RESET}"
        read -r c || c=0
        case "$c" in
            "") continue ;;
            1) pbk_schedule || true; _pool_pause ;;
            2) if pds_enabled; then
                   echo -ne "  DB snapshot is ON. Turn it off? [y/N]: "
                   read -r n || n=""
                   if [[ "${n,,}" == "y" ]]; then pds_disable && success "DB snapshot disabled." || true; fi
               else
                   pds_enable || true
               fi
               _pool_pause ;;
            3) echo -ne "  Interval in minutes — 15, 30, 60 or 120 [current $PDS_INTERVAL]: "
               read -r n || n=""
               if [[ "$n" =~ ^(15|30|60|120)$ ]]; then
                   PDS_INTERVAL="$n"
                   if pbk_save_conf; then
                       if pds_enabled; then _pds_install_cron && success "Interval set to $n min (cron updated)." || true
                       else success "Interval set to $n min (takes effect when the snapshot is turned on)."; fi
                   fi
               elif [[ -n "$n" ]]; then warn "Unchanged — choose 15, 30, 60 or 120."; fi
               _pool_pause ;;
            4) echo -ne "  Keep how many snapshots on this box [current $PDS_KEEP]: "
               read -r n || n=""
               if [[ "$n" =~ ^[0-9]+$ && "$n" -ge 1 ]]; then
                   PDS_KEEP="$n"; pbk_save_conf && success "Snapshot retention set to $n." || true
               elif [[ -n "$n" ]]; then warn "Unchanged (enter a positive number)."; fi
               _pool_pause ;;
            5) _pds_push_settings || true; _pool_pause ;;
            0) return 0 ;;
            *) warn "Invalid option."; sleep 1 ;;
        esac
    done
}

_pds_push_settings() {
    echo ""
    echo -e "  ${DIM}Offsite copies use the shared push target (key 5 on the Backup & Restore screen).${RESET}"
    echo -e "  ${DIM}Remote retention for snapshots is set there in HOURS.${RESET}"
    echo -e "    ${GREEN}1${RESET}) Push every snapshot"
    echo -e "    ${GREEN}2${RESET}) Push at most every N minutes"
    echo -e "    ${GREEN}3${RESET}) Never push snapshots ${DIM}(daily archives are still pushed)${RESET}"
    echo -ne "  Select [1-3, Enter = keep]: "
    local c n; read -r c || c=""
    case "$c" in
        1) PDS_PUSH=1; PDS_PUSH_MIN=0 ;;
        2) echo -ne "  Minimum minutes between snapshot pushes (e.g. 180): "
           read -r n || n=""
           [[ "$n" =~ ^[0-9]+$ && "$n" -ge 1 ]] || { warn "Unchanged (enter a positive number)."; return 1; }
           PDS_PUSH=1; PDS_PUSH_MIN="$n" ;;
        3) PDS_PUSH=0 ;;
        "") info "Unchanged."; return 0 ;;
        *) warn "Invalid choice — unchanged."; return 1 ;;
    esac
    pbk_save_conf || return 1
    success "Snapshot offsite push saved."
}

# ─── Restore a DB snapshot (pool Backup & Restore → 2 → DB snapshot) ─────────
pds_restore() {
    echo -e "\n${BOLD}Pool hub — restore a DB snapshot (${POOL_NET_LABEL:-$POOL_NET})${RESET}"
    command -v openssl >/dev/null 2>&1 || { error "openssl not found — cannot decrypt."; return 1; }
    echo -e "  ${DIM}Replaces pool.db (and, if you say so, the games DB) with the snapshot. Nothing else${RESET}"
    echo -e "  ${DIM}changes: wallet, config and WG identity stay as they are. The current pool.db is${RESET}"
    echo -e "  ${DIM}kept beside it as pool.db.pre-restore-<time>.${RESET}"
    echo ""
    local -a snaps=(); local f i=1 sz sel
    while IFS= read -r f; do [[ -n "$f" ]] && snaps+=("$f"); done \
        < <(ls -t "$PBK_BACKUP_DIR/${PDS_PREFIX}"*.tar.gz.enc 2>/dev/null || true)
    if [[ "${#snaps[@]}" -eq 0 ]]; then
        warn "No ${PDS_PREFIX}* snapshots in $PBK_BACKUP_DIR — copy one there first (scp/rsync)."
        return 1
    fi
    echo -e "  ${BOLD}Snapshots (newest first; date + time in the name are UTC):${RESET}"
    for f in "${snaps[@]}"; do
        if [[ "$i" -le 20 ]]; then
            sz=$(du -sh "$f" 2>/dev/null | cut -f1 || echo "?")
            echo -e "  ${GREEN}$i${RESET}) $(basename "$f")  ${DIM}($sz)${RESET}"
        fi
        i=$((i + 1))
    done
    if [[ "${#snaps[@]}" -gt 20 ]]; then echo -e "  ${DIM}… $(( ${#snaps[@]} - 20 )) older not shown (their numbers still work)${RESET}"; fi
    echo -e "  ${DIM}0) Cancel${RESET}"
    echo -ne "${BOLD}Select snapshot [1-${#snaps[@]}/0]: ${RESET}"
    read -r sel || sel=0
    [[ "$sel" =~ ^[0-9]+$ && "$sel" -ge 1 && "$sel" -le "${#snaps[@]}" ]] || { info "Cancelled."; return 1; }
    local chosen="${snaps[$((sel - 1))]}"
    local d; d=$(pds_parse_date "$chosen") || { error "Not a ${PDS_PREFIX}DDMMYYYY_HHMM.tar.gz.enc name — never rename a snapshot (the date is half its key)."; return 1; }

    local clear key ok=0
    clear=$(mktemp "/tmp/grin_pubpool_dbsnaprestore_XXXXXX.tar.gz") || { error "mktemp failed."; return 1; }
    pbk_load_conf
    if [[ -n "${GBE_PERSONAL_KEY:-}" ]] && gbe_decrypt "$chosen" "$clear" "${GBE_PERSONAL_KEY}${d}"; then
        ok=1; success "Decrypted with this box's saved personal key."
    else
        read -rs -p "  Personal key for this snapshot: " key || key=""; echo ""
        if [[ -n "$key" ]] && gbe_decrypt "$chosen" "$clear" "${key}${d}"; then ok=1; fi
        unset key
    fi
    if [[ "$ok" -ne 1 ]]; then rm -f "$clear"; error "Wrong key or corrupt snapshot."; return 1; fi
    local dbrel="${POOL_APP_DIR#/}/pool.db"
    if ! tar -tzf "$clear" "$dbrel" >/dev/null 2>&1; then
        rm -f "$clear"; error "The snapshot holds no ${POOL_APP_DIR}/pool.db — not this pool's snapshot? Nothing changed."
        return 1
    fi
    success "Decrypted and validated."
    echo ""
    echo -e "  ${RED}${BOLD}This replaces $POOL_APP_DIR/pool.db with the snapshot from $(basename "$chosen").${RESET}"
    echo -e "  ${DIM}Anything the pool recorded after that moment (shares, balances, payouts) is not in it.${RESET}"
    echo -ne "  Type ${BOLD}RESTORE${RESET} to confirm (pool service + wallet listener will be stopped): "
    local go; read -r go || go=""
    [[ "$go" == "RESTORE" ]] || { rm -f "$clear"; info "Restore cancelled — nothing changed."; return 1; }

    local xrc=0
    _pbk_restore_extract "$clear" \
        'ledger restored from a DB snapshot — reconcile before resuming' 'restore' "$dbrel"
    xrc=$?
    if [[ "$xrc" -ne 1 && "$xrc" -ne 4 ]] && declare -F pgs_restore_db_from_archive >/dev/null 2>&1; then
        pgs_restore_db_from_archive "$clear" "$(basename "$chosen")" \
            || warn "Games database not restored — the pool restore continues."
    fi
    rm -f "$clear"
    case "$xrc" in
        0) warn "Payouts FROZEN on the restored ledger — the wallet may have spent money this DB no longer knows about."
           _pbk_report_stratum_pause ;;
        1) error "Extraction failed — pool.db may be missing or partial (disk full? df -h)."
           if [[ -n "${PBK_EXTRACT_ASIDE:-}" ]]; then
               warn "The pool.db that was in place is kept as $PBK_EXTRACT_ASIDE (move it back with its -wal/-shm)."
           fi
           if [[ "$PBK_EXTRACT_FROZEN" != "1" ]]; then
               error "Payouts could NOT be frozen — do NOT start the service; freeze from the admin panel first."
           fi
           _pbk_restore_perms
           return 1 ;;
        2) error "Could not freeze payouts on the restored pool.db."
           error "  Do NOT start the service yet: freeze from the admin panel first."
           _pbk_report_stratum_pause ;;
        4) warn "Nothing was restored — see the message above, then run it again."
           return 1 ;;
        *) : ;;
    esac
    _pbk_restore_perms
    success "DB snapshot restored."
    if [[ -n "${PBK_EXTRACT_ASIDE:-}" ]]; then
        echo -e "  ${DIM}The previous pool.db is kept as $PBK_EXTRACT_ASIDE (+ its -wal/-shm if it had them).${RESET}"
    fi
    echo ""
    echo -e "  ${BOLD}To finish:${RESET}"
    echo -e "    1) ${BOLD}5) Set up wallet → 2) Start listener${RESET} — it was stopped for the restore."
    echo -e "    2) ${BOLD}6) Service control → Start${RESET}, then check admin → health."
    echo -e "    ${RED}3)${RESET} ${BOLD}Reconcile BEFORE resuming payouts${RESET} — admin → Health → Reconciliation."
    echo -e "       ${DIM}Any payout that settled after the snapshot is owed again here but already spent${RESET}"
    echo -e "       ${DIM}on-chain. Resume from admin → Payouts once coverage reports clean.${RESET}"
    if [[ "${PBK_EXTRACT_PAUSED:-0}" == "1" ]]; then
        echo -e "    4) ${BOLD}Resume stratum${RESET} in admin → Announcements → Stratum once the pool checks out."
    fi
    mkdir -p "$(dirname "$PBK_LOG")" 2>/dev/null || true
    echo "[$(date -u '+%Y-%m-%d %H:%M:%S UTC')] restore from DB snapshot: $(basename "$chosen")" >> "$PBK_LOG" 2>/dev/null || true
}

# Restore entry (key 2): full archive or DB snapshot. Goes straight to the full restore
# when there are no snapshots, so the screen is unchanged for a box that never took one.
pool_backup_restore_menu() {
    if ! ls "$PBK_BACKUP_DIR/${PDS_PREFIX}"*.tar.gz.enc >/dev/null 2>&1; then
        pbk_restore; return $?
    fi
    echo ""
    echo -e "  ${GREEN}1${RESET}) Full archive   ${DIM}(pool.db + config + wallet + WG identity — a fresh box starts here)${RESET}"
    echo -e "  ${GREEN}2${RESET}) DB snapshot    ${DIM}(pool.db + games DB only — newer; on top of a full restore, or alone)${RESET}"
    echo -e "  ${DIM}0) Cancel${RESET}"
    echo -ne "${BOLD}Restore what? [1-2/0]: ${RESET}"
    local c; read -r c || c=0
    case "$c" in
        1) pbk_restore ;;
        2) pds_restore ;;
        *) info "Cancelled."; return 1 ;;
    esac
}
