main() {
    while true; do
        show_menu
        local choice; read -r choice
        case "${choice,,}" in
            w) wizard_admin_user     || true ;;
            1) menu_add_key          || true ;;
            2) list_keys             || true ;;
            3) verify_key_login      || true ;;
            4) disable_password_auth || true ;;
            5) commit_hardening      || true ;;
            6) enable_password_auth  || true ;;
            7) ssh_status            || true ;;
            8) connect_help          || true ;;
            0) break ;;
            *) warn "Invalid option."; sleep 1 ;;
        esac
    done
}

main "$@"
