# =============================================================================
# List installed keys
# =============================================================================
list_keys() {
    clear
    echo -e "${BOLD}${CYAN}  Installed authorized keys (root)${RESET}"
    echo ""
    if [[ ! -s "$AUTH_KEYS" ]]; then
        warn "No keys installed yet ($AUTH_KEYS is empty or missing)."
        pause; return 0
    fi
    local n=0 line tmp
    while IFS= read -r line; do
        [[ -z "$line" || "$line" == \#* ]] && continue
        n=$((n + 1))
        tmp="$(mktemp)"; printf '%s\n' "$line" > "$tmp"
        printf "  ${BOLD}%2d)${RESET} %s\n" "$n" "$(ssh-keygen -l -f "$tmp" 2>/dev/null || echo '(unparseable line)')"
        rm -f "$tmp"
    done < "$AUTH_KEYS"
    echo ""
    info "$n key(s) in $AUTH_KEYS"
    pause
}

# =============================================================================
# Anti-lockout self-test — verify key login BEFORE disabling passwords
# =============================================================================

# How did THIS session authenticate? (publickey|password|keyboard-interactive|unknown)
# The strongest proof key auth works: if you're reading this over a key session,
# disabling passwords can't lock you out.
_ssh_current_session_auth() {
    if [[ -z "${SSH_CONNECTION:-}" ]]; then echo "unknown"; return 0; fi
    local cip cport line=""
    cip="$(awk '{print $1}' <<<"$SSH_CONNECTION")"
    cport="$(awk '{print $2}' <<<"$SSH_CONNECTION")"
    if command -v journalctl &>/dev/null; then
        line="$(journalctl _COMM=sshd -n 3000 --no-pager 2>/dev/null \
                | grep -E "Accepted .* from ${cip} port ${cport}( |$)" | tail -1 || true)"
    fi
    if [[ -z "$line" ]]; then
        local f
        for f in /var/log/auth.log /var/log/secure; do
            [[ -r "$f" ]] || continue
            line="$(grep -E "Accepted .* from ${cip} port ${cport}( |$)" "$f" 2>/dev/null | tail -1 || true)"
            [[ -n "$line" ]] && break
        done
    fi
    case "$line" in
        *"Accepted publickey"*)            echo "publickey" ;;
        *"Accepted password"*)             echo "password" ;;
        *"Accepted keyboard-interactive"*) echo "keyboard-interactive" ;;
        *)                                 echo "unknown" ;;
    esac
}

# Real end-to-end key-auth probe: SSH to ourselves using a PRIVATE key, with
# passwords forced off. Returns 0 only if the key alone authenticates.
# Needs the private key on disk (generate-on-server case, or a path the operator
# supplies for a one-off test). $1 = private key path, $2 = user (default root).
_ssh_loopback_test() {
    local key="$1" user="${2:-root}" port host
    [[ -r "$key" ]] || return 2
    command -v ssh &>/dev/null || return 2
    port="$(_ssh_port)"
    for host in 127.0.0.1 "$(awk '{print $3}' <<<"${SSH_CONNECTION:-}")"; do
        [[ -n "$host" ]] || continue
        if ssh -i "$key" -p "$port" \
                -o BatchMode=yes -o StrictHostKeyChecking=no \
                -o UserKnownHostsFile=/dev/null \
                -o PreferredAuthentications=publickey \
                -o PasswordAuthentication=no \
                -o ConnectTimeout=8 \
                "${user}@${host}" true 2>/dev/null; then
            return 0
        fi
    done
    return 1
}

# Pre-flight readiness check. Returns 0 if key login is CONFIRMED safe, else 1.
# When $1 == "quiet" it prints a one-line verdict only (used inside the disable
# flow); otherwise it prints the full report.
verify_key_login() {
    local quiet="${1:-}"
    [[ "$quiet" != "quiet" ]] && { clear; echo -e "${BOLD}${CYAN}  Verify key login (anti-lockout self-test)${RESET}"; echo ""; }

    local keys_ok=0 config_ok=0 pubkey_ok=0 confirmed=0
    local kcount=0
    [[ -s "$AUTH_KEYS" ]] && kcount="$(grep -cvE '^[[:space:]]*($|#)' "$AUTH_KEYS" 2>/dev/null || echo 0)"
    [[ "$kcount" -gt 0 ]] && keys_ok=1

    local meth; meth="$(_ssh_current_session_auth)"

    if [[ "$quiet" != "quiet" ]]; then
        # 1) keys present
        if [[ $keys_ok -eq 1 ]]; then success "authorized_keys: $kcount key(s) installed for root"
        else error "authorized_keys: empty — add a key first (option 1)"; fi

        # 2) perms / ownership
        local dperm fperm downer
        dperm="$(stat -c '%a' /root/.ssh 2>/dev/null || echo '?')"
        fperm="$(stat -c '%a' "$AUTH_KEYS" 2>/dev/null || echo '?')"
        downer="$(stat -c '%U' "$AUTH_KEYS" 2>/dev/null || echo '?')"
        if [[ "$dperm" == "700" && ( "$fperm" == "600" || "$fperm" == "644" ) && "$downer" == "root" ]]; then
            success "Permissions: ~/.ssh=$dperm authorized_keys=$fperm owner=$downer"
        else
            warn "Permissions look off: ~/.ssh=$dperm authorized_keys=$fperm owner=$downer (want 700/600 root)"
        fi
    fi

    # 3) sshd config valid
    if sshd -t 2>/tmp/grin_sshd_err; then
        config_ok=1
        [[ "$quiet" != "quiet" ]] && success "sshd config: valid (sshd -t)"
    else
        [[ "$quiet" != "quiet" ]] && { error "sshd config: INVALID — fix before hardening:"; sed 's/^/      /' /tmp/grin_sshd_err; }
    fi

    # 4) pubkey auth effective for root (honours Match blocks)
    local epub
    epub="$(sshd -T -C user=root 2>/dev/null | awk 'tolower($1)=="pubkeyauthentication"{print $2; exit}')"
    [[ -z "$epub" ]] && epub="$(_ssh_effective pubkeyauthentication)"
    [[ "$epub" == "yes" ]] && pubkey_ok=1
    if [[ "$quiet" != "quiet" ]]; then
        if [[ $pubkey_ok -eq 1 ]]; then success "PubkeyAuthentication: yes (effective for root)"
        else error "PubkeyAuthentication: ${epub:-unknown} — keys won't be accepted"; fi
    fi

    # 5) how the CURRENT session got in
    if [[ "$quiet" != "quiet" ]]; then
        case "$meth" in
            publickey) success "This session authenticated by: ${BOLD}publickey${RESET} ← key login already works" ;;
            password)  warn "This session authenticated by: ${BOLD}password${RESET} — not proof your key works yet" ;;
            keyboard-interactive) warn "This session authenticated by: keyboard-interactive (not pubkey)" ;;
            *)         warn "Could not determine how this session authenticated (no log match)" ;;
        esac
    fi

    # 6) optional real loopback probe with a private key we hold
    local loop_ok=0 priv=""
    priv="$(ls -1t /root/.ssh/grin_ed25519_* 2>/dev/null | grep -v '\.pub$' | head -1 || true)"
    if [[ "$quiet" != "quiet" ]]; then
        if [[ -n "$priv" ]]; then
            info "Loopback key-auth probe using $priv ..."
            if _ssh_loopback_test "$priv"; then loop_ok=1; success "Loopback login with key: SUCCESS"
            else warn "Loopback login with key: failed (server may not accept SSH on localhost — not conclusive)"; fi
        else
            echo -ne "${DIM}  Optional: path to a private key to test now (Enter to skip): ${RESET}"
            local p; read -r p
            if [[ -n "$p" ]]; then
                if _ssh_loopback_test "$p"; then loop_ok=1; success "Loopback login with key: SUCCESS"
                else warn "Loopback login with key: failed or key unreadable"; fi
            fi
        fi
    fi

    # Verdict: confirmed if you're already on a key session, OR a loopback key
    # login succeeded — and the static prerequisites hold.
    if [[ ( "$meth" == "publickey" || $loop_ok -eq 1 ) && $keys_ok -eq 1 && $config_ok -eq 1 && $pubkey_ok -eq 1 ]]; then
        confirmed=1
    fi

    if [[ "$quiet" != "quiet" ]]; then
        echo ""
        local port; port="$(_ssh_port)"
        local sip; sip="$(awk '{print $3}' <<<"${SSH_CONNECTION:-}")"
        if [[ $confirmed -eq 1 ]]; then
            echo -e "${BOLD}${GREEN}  VERDICT: READY — key login is confirmed working.${RESET}"
            echo -e "  Disabling passwords (option 4) is safe; you will not be locked out."
        else
            echo -e "${BOLD}${YELLOW}  VERDICT: NOT CONFIRMED — do NOT disable passwords yet.${RESET}"
            echo ""
            echo -e "  Make it green:"
            [[ $keys_ok -eq 0 ]]   && echo -e "   • add your public key (option 1)"
            [[ $pubkey_ok -eq 0 ]] && echo -e "   • enable PubkeyAuthentication / fix sshd config"
            if [[ "$meth" != "publickey" ]]; then
                echo -e "   • open a NEW terminal and log in with your key:"
                echo -e "       ${DIM}ssh root@${sip:-<server-ip>} -p $port${RESET}"
                echo -e "     then re-run this check — it should turn green."
            fi
            echo -e "  ${DIM}If unsure, use option 4's safety timer: it auto-restores passwords${RESET}"
            echo -e "  ${DIM}unless you confirm you can still get in.${RESET}"
        fi
        pause
    fi

    [[ $confirmed -eq 1 ]]
}

# =============================================================================
# Conflicting-directive detection and (reversible) resolution
# =============================================================================
# sshd keeps the FIRST value it obtains for a keyword. Include expands in
# lexical order, so /etc/ssh/sshd_config.d/50-cloud-init.conf beats a 99- file
# — and `sshd -t` passes, `systemctl reload` returns 0, and the directive is
# simply ignored. Writing the file is not applying the setting.
#
# Rather than model sshd's precedence, these helpers LIST every place a keyword
# is set, let the operator park the ones that are not ours, and then re-ask
# `sshd -T` — which is the only authority on what actually took effect.
#
# Parking is reversible by design: the line keeps its text behind
# $DISABLED_MARK, and _ssh_restore_disabled_lines puts it back verbatim. The
# dead-man timer and break-glass both call that, because a password directive
# left commented out in someone else's file would defeat the rollback.
# =============================================================================

# Every file sshd reads, in the order it reads them (main config first: the
# Include line is at the top on Debian/Ubuntu/Rocky, which is the case that
# matters here).
_ssh_config_files() {
    echo "$SSHD_CONFIG"
    [[ -d "$DROPIN_DIR" ]] || return 0
    local f
    while IFS= read -r f; do
        [[ -n "$f" ]] && echo "$f"
    done < <(find "$DROPIN_DIR" -maxdepth 1 -name '*.conf' -type f 2>/dev/null | LC_ALL=C sort)
}

# Active (uncommented) settings of a keyword: "file:line:text" per match.
# Lines inside a Match block are skipped — they are conditional, not the global
# value, and treating one as the culprit would send the operator after the wrong
# line entirely.
_ssh_keyword_sites() {
    local kw="$1" f
    while IFS= read -r f; do
        [[ -r "$f" ]] || continue
        awk -v kw="$(tr '[:upper:]' '[:lower:]' <<<"$kw")" -v file="$f" '
            { line=$0 }
            tolower($1)=="match" { inmatch=1; next }
            inmatch { next }
            tolower($1)==kw { printf "%s:%d:%s\n", file, NR, line }
        ' "$f" 2>/dev/null
    done < <(_ssh_config_files)
}

# Park one line (by number) behind the marker. The text is preserved exactly.
_ssh_disable_line() {
    local f="$1" n="$2"
    [[ -w "$f" ]] || { error "Not writable: $f"; return 1; }
    cp -a "$f" "$BACKUP_DIR/$(basename "$f").$(date +%Y%m%d_%H%M%S).bak" \
        || { error "Could not back up $f — refusing to edit it"; return 1; }
    sed -i "${n}s|^|${DISABLED_MARK}|" "$f" \
        || { error "Could not edit $f:$n"; return 1; }
    log "Parked $f:$n behind $DISABLED_MARK"
    return 0
}

# Put every parked line back, everywhere. Safe to call when there are none.
_ssh_restore_disabled_lines() {
    local f n=0
    while IFS= read -r f; do
        [[ -w "$f" ]] || continue
        if grep -q "^${DISABLED_MARK}" "$f" 2>/dev/null; then
            sed -i "s|^${DISABLED_MARK}||" "$f" || { error "Could not un-park lines in $f"; return 1; }
            n=$((n + 1))
            log "Restored parked lines in $f"
        fi
    done < <(_ssh_config_files)
    [[ $n -gt 0 ]] && info "Restored original directives in $n file(s)."
    return 0
}

# Show every setting of $1 and offer to park the ones that are not ours.
# Returns 0 if something was changed (worth re-verifying), 1 if not.
_ssh_resolve_conflicts() {
    local kw="$1" sites site f n txt changed=1
    sites="$(_ssh_keyword_sites "$kw")"
    if [[ -z "$sites" ]]; then
        info "No file sets $kw at all — nothing to resolve."
        return 1
    fi

    echo ""
    echo -e "${BOLD}Every active '$kw' setting sshd can see, in read order:${RESET}"
    echo ""
    while IFS= read -r site; do
        [[ -z "$site" ]] && continue
        f="${site%%:*}"; n="${site#*:}"; n="${n%%:*}"; txt="${site#*:*:}"
        if [[ "$f" == "$HARDENING_DROPIN" ]]; then
            echo -e "   ${GREEN}OURS${RESET}  $f:$n"
            echo -e "         ${DIM}$txt${RESET}"
        else
            echo -e "   ${YELLOW}OTHER${RESET} $f:$n"
            echo -e "         ${DIM}$txt${RESET}"
        fi
    done <<<"$sites"
    echo ""
    echo -e "${DIM}sshd uses the FIRST of these it reads — the main config first, then${RESET}"
    echo -e "${DIM}$DROPIN_DIR/*.conf in filename order. Ours is named${RESET}"
    echo -e "${DIM}$(basename "$HARDENING_DROPIN") so it sorts early, but a file in the main${RESET}"
    echo -e "${DIM}config above the Include line still wins.${RESET}"
    echo ""
    echo -e "The fix is to comment the OTHER lines out. The toolkit does it"
    echo -e "reversibly: the text is kept behind ${BOLD}${DISABLED_MARK}${RESET} and put back"
    echo -e "whenever hardening is rolled back (timer, break-glass, or option 6)."
    echo ""
    if ! confirm "Comment out the OTHER '$kw' line(s) and re-check?"; then
        info "Left them alone — nothing changed."
        return 1
    fi

    while IFS= read -r site; do
        [[ -z "$site" ]] && continue
        f="${site%%:*}"; n="${site#*:}"; n="${n%%:*}"
        [[ "$f" == "$HARDENING_DROPIN" ]] && continue
        if _ssh_disable_line "$f" "$n"; then
            success "Commented out $f:$n"
            changed=0
        fi
    done <<<"$sites"

    if [[ $changed -ne 0 ]]; then
        error "Nothing could be changed."
        return 1
    fi
    if ! sshd -t 2>/tmp/grin_sshd_err; then
        error "sshd config is now INVALID — undoing those edits:"
        sed 's/^/    /' /tmp/grin_sshd_err
        _ssh_restore_disabled_lines
        return 1
    fi
    _ssh_service_reload || { error "ssh reload failed after the edit."; return 1; }
    return 0
}

# =============================================================================
# Apply / revert the password-off hardening
# =============================================================================
# Build the directive list ONCE, from the policy file, so the drop-in, the
# in-place block, the dead-man revert and break-glass all agree. With no policy
# file the output is byte-identical to the pre-wizard behaviour (root by key).
_ssh_hardening_directives() {
    local rl admin
    rl="$(_ssh_policy_get ROOT_LOGIN || echo prohibit-password)"
    admin="$(_ssh_policy_get ADMIN_USER || true)"
    echo "PubkeyAuthentication yes"
    echo "PasswordAuthentication no"
    echo "KbdInteractiveAuthentication no"
    echo "PermitRootLogin $rl"
    # AllowUsers is only written when an admin user exists AND root is shut out;
    # otherwise an allow-list would be the one thing standing between the
    # operator and their own root session.
    if [[ -n "$admin" && "$rl" == "no" ]]; then
        echo "AllowUsers $admin"
    fi
}

_ssh_apply_hardening() {
    _ssh_backup_config >/dev/null
    # A leftover 99- file from an older toolkit would sit AFTER ours and shadow
    # nothing, but it is still a second managed file saying the same thing.
    rm -f "$LEGACY_DROPIN" 2>/dev/null || true
    if _ssh_dropin_supported; then
        {
            echo "# Managed by Grin Node Toolkit (085_ssh_hardening.sh) — do not edit by hand."
            _ssh_hardening_directives
        } > "$HARDENING_DROPIN" || { error "Cannot write $HARDENING_DROPIN"; return 1; }
        chmod 644 "$HARDENING_DROPIN"
        log "Wrote drop-in $HARDENING_DROPIN"
    else
        _ssh_remove_managed_block
        {
            echo ""
            echo "$MARK_BEGIN"
            _ssh_hardening_directives
            echo "$MARK_END"
        } >> "$SSHD_CONFIG"
        log "Appended managed block to $SSHD_CONFIG"
    fi

    if ! sshd -t 2>/tmp/grin_sshd_err; then
        error "sshd config validation FAILED — reverting, nothing applied:"
        sed 's/^/    /' /tmp/grin_sshd_err
        _ssh_remove_hardening
        return 1
    fi
    if ! _ssh_service_reload; then
        error "Could not reload the ssh service — reverting to be safe."
        _ssh_remove_hardening
        return 1
    fi
    return 0
}

# Did the drop-in actually TAKE?  sshd uses the FIRST value it obtains for most
# keywords, and some distros place `Include sshd_config.d/*.conf` at the BOTTOM
# of sshd_config — a drop-in there loses to anything set above it. `sshd -t`
# passes either way and `systemctl reload` returns 0, so the only honest check is
# to ask the running config what it resolved to. $1 = expected PermitRootLogin,
# $2 = admin user ("" to skip the allow-list check).
_SSH_FAILED_KEYS=()

_ssh_verify_effective() {
    local want_rl="$1" admin="${2:-}" ok=0
    local pw rl
    _SSH_FAILED_KEYS=()
    pw="$(_ssh_effective passwordauthentication)"
    rl="$(_ssh_effective permitrootlogin)"

    if [[ "$pw" == "no" ]]; then success "Effective PasswordAuthentication: no"
    else
        error "Effective PasswordAuthentication: ${pw:-unknown} — the setting did NOT take"
        _SSH_FAILED_KEYS+=("PasswordAuthentication"); ok=1
    fi

    if [[ "$rl" == "$want_rl" ]]; then success "Effective PermitRootLogin: $rl"
    else
        error "Effective PermitRootLogin: ${rl:-unknown} (wanted $want_rl) — did NOT take"
        _SSH_FAILED_KEYS+=("PermitRootLogin"); ok=1
    fi

    if [[ -n "$admin" ]]; then
        # Ask sshd what it resolves FOR THAT USER — this honours AllowUsers,
        # AllowGroups, DenyUsers and any Match block at once.
        if sshd -T -C "user=$admin" >/dev/null 2>&1; then
            success "sshd resolves a config for '$admin' (not blocked by an allow/deny rule)"
        else
            error "sshd -T -C user=$admin FAILED — '$admin' may be blocked from logging in"; ok=1
        fi
    fi

    if [[ $ok -ne 0 ]]; then
        echo ""
        warn "The directive IS in $HARDENING_DROPIN, but sshd kept an earlier value."
        warn "sshd uses the FIRST value it obtains, and Include reads"
        warn "$DROPIN_DIR/*.conf in FILENAME order — so a lower-numbered"
        warn "file wins. On Ubuntu that is usually 50-cloud-init.conf."
        local k
        if [[ ${#_SSH_FAILED_KEYS[@]} -gt 0 ]]; then
            for k in "${_SSH_FAILED_KEYS[@]}"; do
                echo ""
                warn "Every active '$k' line sshd can see:"
                _ssh_keyword_sites "$k" | sed 's/^/      /'
            done
        fi
        return 1
    fi
    return 0
}

# Post-apply gate: verify, and when a directive did not take, show exactly which
# file beat it and offer the reversible fix, then verify again. Loops until the
# config is right, the operator stops, or there is nothing left to try.
# Returns 0 only when everything resolved. $1 = expected PermitRootLogin,
# $2 = admin user ("" to skip the per-user check).
_ssh_postapply_gate() {
    local want_rl="$1" admin="${2:-}" k
    while true; do
        if _ssh_verify_effective "$want_rl" "$admin"; then
            return 0
        fi
        if [[ ${#_SSH_FAILED_KEYS[@]} -eq 0 ]]; then
            # Failed for a reason conflict-resolution cannot fix (e.g. the user
            # is blocked by an allow/deny rule we did not write).
            return 1
        fi
        echo ""
        echo -e "${BOLD}This is fixable${RESET} — the directive is written, but another file sets the"
        echo -e "same keyword earlier, and sshd keeps the first value it reads."
        echo ""
        echo -e "  ${BOLD}f${RESET}) show the conflicting lines and comment them out (reversible)"
        echo -e "  ${BOLD}q${RESET}) stop and roll the hardening back"
        echo -ne "${BOLD}Choose [f/q]: ${RESET}"
        local c
        if ! read -r c; then
            echo ""
            warn "No input available — rolling back."
            return 1
        fi
        [[ "${c,,}" != "f" ]] && return 1

        local progressed=1
        for k in "${_SSH_FAILED_KEYS[@]}"; do
            if _ssh_resolve_conflicts "$k"; then progressed=0; fi
        done
        if [[ $progressed -ne 0 ]]; then
            warn "Nothing was changed, so the result would be the same."
            return 1
        fi
        echo ""
        info "Re-checking what sshd resolves now ..."
    done
}

_ssh_revert_hardening() {
    _ssh_backup_config >/dev/null
    _ssh_remove_hardening
    if ! sshd -t 2>/tmp/grin_sshd_err; then
        error "sshd config invalid after revert — manual check needed:"
        sed 's/^/    /' /tmp/grin_sshd_err
        return 1
    fi
    _ssh_service_reload || { error "ssh reload failed."; return 1; }
    return 0
}

# =============================================================================
# Dead-man safety timer
# =============================================================================
# An armed timer is two independent safety nets around ONE persistent marker,
# $AUTOREVERT_STATE:
#   · a countdown — a transient systemd timer (systemd-run), or a nohup sleep
#     on a host without systemd — that runs $AUTOREVERT_SH when it expires;
#   · a boot guard — the persistent $AUTOREVERT_UNIT, which runs the same
#     script at boot while the marker exists.
# A countdown of either kind dies with a reboot; the boot guard is what makes a
# reboot inside the window safe. A reboot before the operator confirmed counts
# as "not confirmed", so the change is undone at boot whatever the deadline.
# The script does nothing once the marker is gone, so confirming (option 5)
# only has to delete the marker to disarm both nets; stopping the timer and
# disabling the guard is tidying up.
#
# Life of one change:
#   supersede  take over an earlier unconfirmed change (see below)
#   arm        script + marker + boot guard, BEFORE sshd is touched, so a
#              reboot at any point after the apply starts is covered
#   (apply + verify; a session that dies here starts the countdown on exit)
#   start      the countdown, once the change is verified; it carries the
#              marker's ID, so a stale countdown cannot act on a newer arming
#   cancel     confirmed: delete the marker            (option 5)
#   abort      failed before start: put the policy back and delete the marker
#
# A guided-setup run sets POLICY_RESTORE=1 and hands the undo the policy file
# it replaced ($AUTOREVERT_POLICY_PREV; absent = there was none). An earlier
# change that is still unconfirmed is never just cancelled by a new run: its
# saved policy is carried into the new run, because undoing the new change
# removes the earlier one too and must restore the policy from before BOTH.
#
# The undo script and every disarm path share a flock on $AUTOREVERT_LOCK, so a
# cancel can never report success for an undo that was already running. Hosts
# without flock skip the lock.
# =============================================================================
_SSH_SUPERSEDED="none"      # none | plain | policy — set by _ssh_autorevert_supersede
_SSH_ARMED_THIS_RUN=0       # 1 once this run's _ssh_autorevert_arm succeeded

_ssh_have_systemd() {
    command -v systemctl >/dev/null 2>&1 && command -v systemd-run >/dev/null 2>&1 \
        && [[ -d /run/systemd/system ]]
}

_ssh_autorevert_state_get() {
    [[ -r "$AUTOREVERT_STATE" ]] || return 1
    sed -n "s/^$1=//p" "$AUTOREVERT_STATE" 2>/dev/null | head -1
}

# A change is waiting for confirmation (whether or not its countdown still runs).
_ssh_autorevert_pending() {
    [[ -f "$AUTOREVERT_STATE" ]]
}

# The countdown is really running. The pid file alone also covers a timer
# armed by an older toolkit, which wrote no marker.
_ssh_autorevert_active() {
    local unit pid
    unit="$(_ssh_autorevert_state_get UNIT || true)"
    if [[ -n "$unit" ]] && command -v systemctl >/dev/null 2>&1 \
        && systemctl is-active --quiet "$unit.timer" 2>/dev/null; then
        return 0
    fi
    pid="$(cat "$AUTOREVERT_PID" 2>/dev/null || true)"
    [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null
}

# Is the boot guard installed and enabled?
_ssh_autorevert_boot_guarded() {
    command -v systemctl >/dev/null 2>&1 \
        && systemctl is-enabled --quiet "$AUTOREVERT_UNIT" 2>/dev/null
}

# Hold the shared lock on fd 8. Returns 1 only when the lock is busy for a
# minute (an undo that does not finish); no flock = no lock, return 0.
# Release with _ssh_autorevert_unlock before starting any long-lived process,
# which would inherit fd 8 and keep the lock held.
_ssh_autorevert_lock() {
    command -v flock >/dev/null 2>&1 || return 0
    exec 8>"$AUTOREVERT_LOCK" || return 0
    if ! flock -w 60 8; then
        exec 8>&-
        error "The safety-timer lock is busy (an undo may be running) — try again in a minute."
        return 1
    fi
    return 0
}
_ssh_autorevert_unlock() {
    command -v flock >/dev/null 2>&1 || return 0
    exec 8>&-
    return 0
}

# Write the standalone undo script. Standalone by design: it must undo the
# change with no help from the toolkit, so it repeats the removal inline rather
# than sourcing anything. It undoes ALL THREE parts of an apply — our drop-in,
# the in-place marked block, and any directive we parked in another file — or
# the "passwords come back on their own" promise is false. Written to a temp
# file and renamed: a countdown armed by an older toolkit may still be reading
# the old file, and bash reads a script as it runs.
# At boot it runs before basic.target (see _ssh_install_boot_guard), so it uses
# only coreutils/sed/grep/flock/systemctl. The unit is ordered after the journal
# socket, and the message also goes to stdout in case logger fails.
_ssh_write_autorevert_script() {
    local tmp="$AUTOREVERT_SH.tmp.$$"
    cat > "$tmp" <<EOF || { error "Cannot write $tmp"; rm -f "$tmp"; return 1; }
#!/bin/bash
# Grin Node Toolkit (085_ssh_hardening.sh) — SSH hardening auto-undo.
# Run as "\$0 <ID>" by the countdown timer, or "\$0 boot" by $AUTOREVERT_UNIT.
# It acts only while $AUTOREVERT_STATE exists: confirming deletes that file, so a
# confirmed change is never undone.
STATE="$AUTOREVERT_STATE"
ARG="\${1:-}"
# Held for the whole run, so the toolkit's cancel waits for an undo in progress
# and then sees the marker gone. Without flock the undo runs unlocked.
if command -v flock >/dev/null 2>&1 && exec 9>"$AUTOREVERT_LOCK"; then
    flock -w 120 9
fi
[ -f "\$STATE" ] || exit 0
# A countdown acts only on the arming it was started for: one from an earlier
# arming that wakes late must not undo (or take the policy of) a newer change.
# Any boot before confirmation undoes whatever is armed.
ID="\$(sed -n 's/^ID=//p' "\$STATE" | head -1)"
if [ "\$ARG" != "boot" ] && { [ -z "\$ID" ] || [ "\$ARG" != "\$ID" ]; }; then
    exit 0
fi
UNIT="\$(sed -n 's/^UNIT=//p' "\$STATE" | head -1)"
rm -f "$HARDENING_DROPIN" "$LEGACY_DROPIN" 2>/dev/null
sed -i "/$MARK_BEGIN/,/$MARK_END/d" "$SSHD_CONFIG" 2>/dev/null
for f in "$SSHD_CONFIG" "$DROPIN_DIR"/*.conf; do
    [ -f "\$f" ] || continue
    sed -i "s|^${DISABLED_MARK}||" "\$f" 2>/dev/null
done
# A guided-setup run puts back the policy it replaced, so option 4 cannot
# re-apply the policy this undo just took away.
if grep -qx 'POLICY_RESTORE=1' "\$STATE"; then
    if [ -f "$AUTOREVERT_POLICY_PREV" ]; then
        mv -f "$AUTOREVERT_POLICY_PREV" "$POLICY_CONF" 2>/dev/null
    else
        rm -f "$POLICY_CONF" 2>/dev/null
    fi
fi
rm -f "$AUTOREVERT_POLICY_PREV" 2>/dev/null
# Only a RUNNING daemon is validated and reloaded. At boot this runs before
# sshd starts (and before /run/sshd exists, which makes \`sshd -t\` fail on
# Debian/Ubuntu); sshd then simply starts from the restored files.
running=""
if command -v systemctl >/dev/null 2>&1; then
    for u in ssh sshd; do
        if systemctl is-active --quiet "\$u" 2>/dev/null; then running="\$u"; break; fi
    done
elif pgrep -x sshd >/dev/null 2>&1; then
    running="service"
fi
if [ -z "\$running" ]; then
    msg="unconfirmed SSH hardening undone: sshd starts with password login restored"
elif sshd -t 2>/dev/null; then
    if [ "\$running" = "service" ]; then
        service ssh reload 2>/dev/null || service sshd reload 2>/dev/null
    else
        systemctl reload "\$running" 2>/dev/null
    fi
    msg="unconfirmed SSH hardening undone: password login restored"
else
    msg="unconfirmed SSH hardening undone, but sshd -t FAILS: fix the sshd config from the provider console"
fi
rm -f "\$STATE" "$AUTOREVERT_PID" 2>/dev/null
if command -v systemctl >/dev/null 2>&1; then
    systemctl disable --no-reload "$AUTOREVERT_UNIT" >/dev/null 2>&1
    [ -n "\$UNIT" ] && systemctl stop "\$UNIT.timer" >/dev/null 2>&1
fi
# stdout reaches the journal under systemd even when logger cannot (early boot).
echo "grin-ssh-autorevert: \$msg"
command -v logger >/dev/null 2>&1 && logger -t grin-ssh-autorevert "\$msg" 2>/dev/null
exit 0
EOF
    chmod 700 "$tmp" || { error "Cannot chmod $tmp"; rm -f "$tmp"; return 1; }
    mv -f "$tmp" "$AUTOREVERT_SH" || { error "Cannot move $tmp to $AUTOREVERT_SH"; rm -f "$tmp"; return 1; }
    return 0
}

# Install + enable the boot guard. Returns 1 when it could not be installed;
# the caller still has a countdown but must warn about the reboot gap.
# DefaultDependencies=no is required, not cosmetic: the default After=basic.target
# plus Before=ssh.socket is an ordering cycle (ssh.socket is Before=sockets.target,
# which basic.target is After), and systemd breaks a cycle by dropping a job —
# the guard (nothing reverts) or ssh.socket (nothing listens). Ordering before
# sockets.target covers socket-activated sshd (Ubuntu 22.10+) as well.
# After=systemd-journald.socket is cycle-free here (that socket is itself
# DefaultDependencies=no and Before=sockets.target) and gives logger a journal.
_ssh_install_boot_guard() {
    _ssh_have_systemd || return 1
    cat > "$AUTOREVERT_UNIT_FILE" <<EOF || { error "Cannot write $AUTOREVERT_UNIT_FILE"; return 1; }
# Managed by Grin Node Toolkit (085_ssh_hardening.sh) — do not edit by hand.
# Undoes SSH hardening that was applied with a safety timer and never confirmed
# when the box reboots inside the timer window. Inert unless the marker exists.
[Unit]
Description=Grin Node Toolkit: undo unconfirmed SSH hardening at boot
ConditionPathExists=$AUTOREVERT_STATE
DefaultDependencies=no
RequiresMountsFor=$CONF_DIR
After=local-fs.target systemd-journald.socket
Before=sockets.target ssh.socket ssh.service sshd.service shutdown.target
Conflicts=shutdown.target

[Service]
Type=oneshot
ExecStart=/bin/bash $AUTOREVERT_SH boot

[Install]
WantedBy=multi-user.target
EOF
    systemctl daemon-reload >/dev/null 2>&1 || { error "systemctl daemon-reload failed"; return 1; }
    systemctl enable "$AUTOREVERT_UNIT" >/dev/null 2>&1 \
        || { error "Cannot enable $AUTOREVERT_UNIT"; return 1; }
    return 0
}

# Delete the marker and stop everything that serves it. Caller holds the lock.
# Returns 0 when something was disarmed, 2 when nothing was armed (or an undo
# got there first), 1 when the marker could not be deleted.
_ssh_autorevert_disarm_locked() {
    local unit pid had=0
    unit="$(_ssh_autorevert_state_get UNIT || true)"
    pid="$(cat "$AUTOREVERT_PID" 2>/dev/null || true)"
    if [[ -e "$AUTOREVERT_STATE" ]]; then
        rm -f "$AUTOREVERT_STATE" || { error "Cannot delete $AUTOREVERT_STATE — the timer is still armed"; return 1; }
        had=1
    fi
    if command -v systemctl >/dev/null 2>&1; then
        if [[ -n "$unit" ]]; then
            systemctl stop "$unit.timer" >/dev/null 2>&1 || true
            systemctl reset-failed "$unit.timer" "$unit.service" >/dev/null 2>&1 || true
        fi
        systemctl disable "$AUTOREVERT_UNIT" >/dev/null 2>&1 || true
    fi
    # The nohup countdown, and one armed by an older toolkit (which has no
    # marker to check), are stopped by pid. KILL, because a countdown started
    # from the armed-window handler inherits "ignore TERM", and bash cannot
    # un-ignore a signal that was ignored when it started.
    if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
        kill -KILL "$pid" 2>/dev/null || true
        had=1
    fi
    rm -f "$AUTOREVERT_PID" "$AUTOREVERT_SH" "$AUTOREVERT_POLICY_PREV" 2>/dev/null || true
    if [[ $had -eq 1 ]]; then return 0; fi
    return 2
}

# Confirmed: disarm. Returns 0 disarmed, 2 nothing was armed (an undo may have
# run just before), 1 still armed.
_ssh_cancel_autorevert() {
    local rc=0
    _ssh_autorevert_lock || return 1
    _ssh_autorevert_disarm_locked || rc=$?
    _ssh_autorevert_unlock
    return $rc
}

# Take over an earlier unconfirmed change before a new one is applied, so its
# countdown cannot fire in the middle of the new apply. Sets _SSH_SUPERSEDED:
#   none    nothing was pending
#   plain   a change was pending; it stays in place with its timer stopped, so
#           the caller must re-arm or undo it
#   policy  same, and it carried a policy restore: its saved policy moves to
#           $POLICY_STASH (absent = there was none), for the caller to carry on
# Returns 1 (nothing changed) if the lock or the stash move failed.
_ssh_autorevert_supersede() {
    local rc=0
    _SSH_SUPERSEDED="none"
    _SSH_ARMED_THIS_RUN=0
    _ssh_autorevert_lock || return 1
    if _ssh_autorevert_pending && grep -qx 'POLICY_RESTORE=1' "$AUTOREVERT_STATE" 2>/dev/null; then
        _ssh_policy_move "$AUTOREVERT_POLICY_PREV" "$POLICY_STASH" || { _ssh_autorevert_unlock; return 1; }
        _SSH_SUPERSEDED="policy"
    fi
    _ssh_autorevert_disarm_locked || rc=$?
    _ssh_autorevert_unlock
    case "$rc" in
        0) [[ "$_SSH_SUPERSEDED" == "none" ]] && _SSH_SUPERSEDED="plain"
           info "An earlier unconfirmed change was pending — this run takes it over (its timer is stopped)." ;;
        2) _SSH_SUPERSEDED="none" ;;
        *) if [[ "$_SSH_SUPERSEDED" == "policy" && -f "$POLICY_STASH" ]]; then
               mv -f "$POLICY_STASH" "$AUTOREVERT_POLICY_PREV" || true
           fi
           _SSH_SUPERSEDED="none"
           return 1 ;;
    esac
    return 0
}

# Arm the marker, script and boot guard — no countdown yet. Call BEFORE the
# apply. $1 (optional) = a stashed policy file (see _ssh_policy_stash) that the
# undo restores; passing it sets POLICY_RESTORE=1 even when the file is absent
# (= there was no policy). On failure the stash is left where it was.
# The marker carries a random ID that the countdown passes to the script, so a
# countdown from an earlier arming that wakes late cannot act on this one.
_ssh_autorevert_arm() {
    local stash="${1:-}" restore=0 id
    [[ -n "$stash" ]] && restore=1
    id="$(od -An -N8 -tx1 /dev/urandom 2>/dev/null | tr -d ' \n' || true)"
    [[ -n "$id" ]] || id="$$-$RANDOM-$(date +%s)"
    _ssh_write_autorevert_script || return 1
    printf 'ID=%s\nPOLICY_RESTORE=%s\n' "$id" "$restore" > "$AUTOREVERT_STATE" \
        || { error "Cannot write $AUTOREVERT_STATE"; rm -f "$AUTOREVERT_STATE" 2>/dev/null; return 1; }
    chmod 600 "$AUTOREVERT_STATE" \
        || { error "Cannot chmod $AUTOREVERT_STATE"; rm -f "$AUTOREVERT_STATE" 2>/dev/null; return 1; }
    if [[ -n "$stash" ]] && ! _ssh_policy_move "$stash" "$AUTOREVERT_POLICY_PREV"; then
        rm -f "$AUTOREVERT_STATE" 2>/dev/null || true
        return 1
    fi
    if _ssh_install_boot_guard; then
        log "Boot guard $AUTOREVERT_UNIT enabled"
    else
        warn "Could not install the boot guard ($AUTOREVERT_UNIT; systemd is needed)."
        warn "If this server REBOOTS before you confirm, the change will NOT be undone"
        warn "— keep this session open and do not reboot until key login is proven."
    fi
    _SSH_ARMED_THIS_RUN=1
    return 0
}

# Start the countdown on an armed marker: undo in $1 minutes unless confirmed.
# Returns 1 when NO countdown could be started — the caller must then roll the
# change back itself (_ssh_rollback_change).
_ssh_autorevert_start() {
    local mins="$1" secs deadline unit pid id
    _ssh_autorevert_pending || { error "The safety timer is not armed."; return 1; }
    id="$(_ssh_autorevert_state_get ID || true)"
    secs=$(( 10#$mins * 60 ))
    deadline=$(( $(date +%s) + secs ))
    printf 'DEADLINE=%s\n' "$deadline" >> "$AUTOREVERT_STATE" \
        || { error "Cannot write $AUTOREVERT_STATE"; return 1; }

    if _ssh_have_systemd; then
        unit="grin-ssh-undo-$(date +%Y%m%d%H%M%S)"
        if systemd-run --unit="$unit" \
                --description="Grin Node Toolkit: SSH hardening auto-undo" \
                --on-active="${secs}s" --timer-property=AccuracySec=1s \
                /bin/bash "$AUTOREVERT_SH" "$id" >/dev/null 2>&1; then
            printf 'UNIT=%s\n' "$unit" >> "$AUTOREVERT_STATE" \
                || error "Cannot record the timer unit in $AUTOREVERT_STATE"
            log "Scheduled auto-revert in $mins min ($unit.timer, deadline $deadline)"
            return 0
        fi
        warn "systemd-run could not arm the timer — falling back to a background process."
    fi

    # fd 8 closed so the countdown never holds the shared lock.
    nohup bash -c "sleep $secs; exec /bin/bash '$AUTOREVERT_SH' '$id'" >/dev/null 2>&1 8>&- &
    pid=$!
    if ! kill -0 "$pid" 2>/dev/null; then
        error "Could not start the auto-undo countdown."
        return 1
    fi
    echo "$pid" > "$AUTOREVERT_PID" || error "Cannot write $AUTOREVERT_PID"
    log "Scheduled auto-revert in $mins min (pid $pid, deadline $deadline)"
    return 0
}

# The change failed before (or while) the countdown started: put back the
# policy the marker saved, then disarm. The sshd revert is the caller's job.
_ssh_autorevert_abort() {
    _ssh_autorevert_lock || return 1
    if _ssh_autorevert_pending && grep -qx 'POLICY_RESTORE=1' "$AUTOREVERT_STATE" 2>/dev/null; then
        if _ssh_policy_move "$AUTOREVERT_POLICY_PREV" "$POLICY_CONF"; then
            log "Policy restored to its state before this run"
        fi
    fi
    _ssh_autorevert_disarm_locked || true
    _ssh_autorevert_unlock
    return 0
}

# Between arm and start the change is covered only at boot. If the session dies
# there (SSH drop = SIGHUP, Ctrl-C, kill), start the countdown on the way out —
# the operator may be cut off and unable to roll back — so the change is undone
# on time; if no countdown can start, revert at once. The handler ignores
# further signals first, so it runs once. Only a Ctrl-C (the terminal is still
# there) gets a line of output.
_SSH_ARMED_MINS=""
_ssh_armed_trap_set() {
    _SSH_ARMED_MINS="$1"
    trap '_ssh_armed_trap_fire HUP' HUP
    trap '_ssh_armed_trap_fire INT' INT
    trap '_ssh_armed_trap_fire TERM' TERM
}
_ssh_armed_trap_clear() {
    trap - HUP INT TERM
    _SSH_ARMED_MINS=""
}
_ssh_armed_trap_fire() {
    local sig="$1"
    trap '' HUP INT TERM
    if [[ -n "$_SSH_ARMED_MINS" ]] && _ssh_autorevert_pending; then
        if _ssh_autorevert_start "$_SSH_ARMED_MINS" >/dev/null 2>&1; then
            log "Session ended ($sig) while armed — countdown started on exit"
            if [[ "$sig" == "INT" ]]; then
                echo "Interrupted — the ${_SSH_ARMED_MINS}-minute auto-undo is running; confirm with option 5." 2>/dev/null || true
            fi
        else
            _ssh_revert_hardening >/dev/null 2>&1 || true
            log "Session ended ($sig) while armed — countdown FAILED, reverted"
        fi
    fi
    exit 1
}

# Undo a change that failed after its confirm prompt (option 4 and the guided
# setup share this). $1 = 1 once the sshd apply was attempted, $2 = 1 once
# $POLICY_STASH holds the policy to go back to. An earlier unconfirmed change
# this run took over is undone as well: its own timer is gone, and the
# dead-man promise was that it would not survive unconfirmed.
# The revert always reloads sshd: a failed apply removes the files but leaves
# the running daemon on the previous config.
_ssh_rollback_change() {
    local applied="$1" stashed="$2"
    if [[ "$_SSH_SUPERSEDED" != "none" ]]; then
        warn "Undoing the earlier unconfirmed change too — this run took over its timer."
    fi
    if [[ "$applied" == "1" || "$_SSH_SUPERSEDED" != "none" ]]; then
        if [[ "$applied" == "1" ]]; then
            warn "This removes ALL toolkit SSH hardening, including any applied and confirmed earlier."
        fi
        _ssh_revert_hardening || error "Rollback FAILED — fix $SSHD_CONFIG by hand NOW, in this session."
    fi
    _ssh_armed_trap_clear
    if _ssh_autorevert_pending; then
        # Armed: the marker owns the saved policy; abort puts it back.
        _ssh_autorevert_abort || true
    elif [[ "$_SSH_ARMED_THIS_RUN" == "1" ]]; then
        # Armed, and the marker is gone: the countdown already fired, and the
        # undo put the policy back. The stash went to it, so unstashing now
        # would delete that restored policy.
        :
    elif [[ "$stashed" == "1" ]]; then
        _ssh_policy_unstash || true
    fi
    _SSH_SUPERSEDED="none"
    _SSH_ARMED_THIS_RUN=0
    return 0
}

# =============================================================================
# Disable password login (key-only)
# =============================================================================
disable_password_auth() {
    clear
    echo -e "${BOLD}${CYAN}  Disable password login (key-only root access)${RESET}"
    echo ""

    if [[ ! -s "$AUTH_KEYS" ]]; then
        error "No authorized keys installed — add a key first (option 1)."
        error "Disabling passwords now would LOCK YOU OUT."
        pause; return 0
    fi

    local kcount
    kcount="$(grep -cvE '^[[:space:]]*($|#)' "$AUTH_KEYS" 2>/dev/null || echo 0)"
    info "$kcount key(s) currently authorized for root."

    # A policy left by the guided setup makes this option do MORE than its name
    # says — surface it rather than silently shutting root out of SSH.
    if [[ "$(_ssh_policy_get ROOT_LOGIN || echo prohibit-password)" == "no" ]]; then
        echo ""
        warn "A stored policy from the guided setup is in effect: applying here will"
        warn "ALSO set PermitRootLogin no (admin user: $(_ssh_policy_get ADMIN_USER || echo none))."
        warn "Prefer the wizard (W) for its proof gates; option 6 can clear the policy."
    fi

    # Anti-lockout pre-flight — surface the verdict before any change.
    if verify_key_login quiet; then
        success "Self-test: key login is CONFIRMED working (this session is key-authenticated)."
    else
        local _m; _m="$(_ssh_current_session_auth)"
        warn "Self-test: key login NOT confirmed (current session: ${_m})."
        warn "Run option 3 (Verify key login) for details — or use the safety timer below."
    fi

    # Firewall sanity — is the SSH port reachable?
    local port; port="$(_ssh_port)"
    if command -v ufw &>/dev/null && ufw status 2>/dev/null | grep -qi '^Status: active'; then
        if ufw status 2>/dev/null | grep -qE "(^|[[:space:]])$port(/tcp)?[[:space:]]"; then
            info "UFW: port $port appears allowed."
        else
            warn "UFW is active but no explicit rule for SSH port $port was found."
            warn "Make sure you can still reach the server on port $port."
        fi
    fi

    echo ""
    echo -e "${BOLD}${YELLOW}IMPORTANT — verify key login BEFORE relying on this.${RESET}"
    echo -e "Open a ${BOLD}second${RESET} terminal and confirm: ${DIM}ssh root@<server-ip> -p $port${RESET}"
    echo -e "logs in using your key (no password prompt)."
    echo ""
    echo -e "Two ways to proceed safely:"
    echo -e "  ${BOLD}A)${RESET} Safety timer — apply now, passwords auto-restore in N minutes"
    echo -e "     unless you commit with option 5. Best if you haven't tested yet."
    echo -e "  ${BOLD}B)${RESET} Apply permanently — only if you've ALREADY confirmed key login."
    echo ""
    echo -ne "${BOLD}Choose [A/b]: ${RESET}"
    local mode; read -r mode
    mode="${mode:-A}"

    # From each confirm prompt on, every failure goes through _ssh_rollback_change,
    # which reverts AND reloads sshd, undoes an earlier unconfirmed change this
    # run took over, and puts back the policy that change was owed.
    local stashed=0
    if [[ "${mode,,}" == "b" ]]; then
        if ! confirm "Confirm: you have ALREADY logged in with your key in another session?"; then
            info "Aborted — nothing changed."; pause; return 0
        fi
        # An earlier unconfirmed change is taken over first, so its countdown
        # cannot fire in the middle of this apply.
        _ssh_autorevert_supersede || { info "Nothing changed."; pause; return 0; }
        if [[ "$_SSH_SUPERSEDED" == "policy" ]]; then stashed=1; fi
        if ! _ssh_apply_hardening; then
            error "Hardening not applied (see above) — rolling back to password login."
            _ssh_rollback_change 1 "$stashed"
            pause; return 0
        fi
        echo ""
        info "Checking what sshd actually resolved (not just what we wrote) ..."
        if ! _ssh_postapply_gate "$(_ssh_policy_get ROOT_LOGIN || echo prohibit-password)" ""; then
            warn "The change did not take effect — rolling it back rather than"
            warn "leaving you in a half-applied state."
            _ssh_rollback_change 1 "$stashed"
            pause; return 0
        fi
        # Permanent: an earlier unconfirmed change is confirmed along with it.
        rm -f "$POLICY_STASH" 2>/dev/null || true
        success "Password authentication DISABLED. Login is key-only now."
        pause; return 0
    fi

    # Mode A — dead-man safety timer
    echo -ne "${BOLD}Auto-restore passwords after how many minutes? [5]: ${RESET}"
    local mins; read -r mins
    mins="${mins:-5}"
    # Base 10 forced: "08" passes the regex but is invalid octal in arithmetic.
    if [[ "$mins" =~ ^[0-9]{1,5}$ ]]; then mins=$((10#$mins)); else mins=5; fi
    if [[ "$mins" -lt 1 ]]; then mins=5; fi

    if ! confirm "Apply key-only login now with a ${mins}-minute safety timer?"; then
        info "Aborted — nothing changed."; pause; return 0
    fi

    # Armed BEFORE the apply, so a reboot at any point from here on undoes it.
    # A policy restore owed by an earlier unconfirmed run is carried over.
    _ssh_autorevert_supersede || { info "Nothing changed."; pause; return 0; }
    local carry=""
    if [[ "$_SSH_SUPERSEDED" == "policy" ]]; then carry="$POLICY_STASH"; stashed=1; fi
    if ! _ssh_autorevert_arm "$carry"; then
        error "The safety timer could not be armed — nothing applied."
        _ssh_rollback_change 0 "$stashed"
        pause; return 0
    fi
    _ssh_armed_trap_set "$mins"

    if ! _ssh_apply_hardening; then
        error "Hardening not applied (see above) — rolling back to password login."
        _ssh_rollback_change 1 "$stashed"
        pause; return 0
    fi
    # The countdown starts BEFORE the check below: that check waits for input,
    # and a session cut off there with no SIGHUP (tmux, screen) must still be
    # undone on time. A failed check rolls back, which disarms the countdown.
    if ! _ssh_autorevert_start "$mins"; then
        error "The safety timer could not be started — rolling the change back rather"
        error "than leaving key-only login in place with no undo."
        _ssh_rollback_change 1 "$stashed"
        pause; return 0
    fi
    _ssh_armed_trap_clear
    echo ""
    info "Checking what sshd actually resolved (not just what we wrote) ..."
    if ! _ssh_postapply_gate "$(_ssh_policy_get ROOT_LOGIN || echo prohibit-password)" ""; then
        warn "The change did not take effect — rolling it back. Nothing is half-applied,"
        warn "and the timer is disarmed."
        _ssh_rollback_change 1 "$stashed"
        pause; return 0
    fi
    if ! _ssh_autorevert_pending; then
        warn "The ${mins}-minute timer ran out during the check above, and the change"
        warn "has been undone: password login is back. Run option 4 again."
        pause; return 0
    fi
    echo ""
    success "Password login DISABLED with a ${mins}-minute safety timer."
    if _ssh_autorevert_boot_guarded; then
        info "A reboot before you commit also undoes it (boot guard $AUTOREVERT_UNIT)."
    fi
    echo ""
    echo -e "${BOLD}Now, in another terminal:${RESET} ${DIM}ssh root@<server-ip> -p $port${RESET}"
    echo -e "  • If key login works  → return here and run ${BOLD}option 5${RESET} to make it permanent."
    echo -e "  • If you get locked out → do nothing; passwords auto-restore in ${mins} min."
    if _ssh_autorevert_boot_guarded; then
        echo -e "    (Or reboot the server from the provider panel — that undoes it at once.)"
    fi
    pause
}

# =============================================================================
# Commit — cancel the safety timer, keep key-only login
# =============================================================================
commit_hardening() {
    clear
    echo -e "${BOLD}${CYAN}  Make key-only login permanent${RESET}"
    echo ""
    if [[ "$(_ssh_effective passwordauthentication)" != "no" ]]; then
        warn "Password authentication is currently ENABLED — nothing to commit."
        warn "Run option 4 first to disable it."
        pause; return 0
    fi
    if _ssh_autorevert_pending || _ssh_autorevert_active; then
        if ! _ssh_autorevert_active; then
            warn "The change is still unconfirmed, but its countdown is no longer running."
            if _ssh_autorevert_boot_guarded; then
                warn "It will be undone at the next boot unless you confirm it here."
            fi
        fi
        if confirm "Key login confirmed working — cancel the safety timer and keep key-only login?"; then
            local crc=0
            _ssh_cancel_autorevert || crc=$?
            case "$crc" in
                0) success "Safety timer cancelled. Key-only root login is now permanent."
                   success "A reboot no longer undoes it." ;;
                2) warn "Too late — the timer fired just before this, and the change has been"
                   warn "undone: password login is back. Re-apply with option 4 or the wizard." ;;
                *) error "The timer is still armed — the change may yet be undone." ;;
            esac
        else
            info "Left the safety timer running."
        fi
    else
        info "No safety timer is running — key-only login is already permanent."
    fi
    pause
}

# =============================================================================
# Re-enable password login (rollback / break-glass)
# =============================================================================
enable_password_auth() {
    clear
    echo -e "${BOLD}${CYAN}  Re-enable password login (rollback)${RESET}"
    echo ""
    if ! confirm "Re-enable SSH password authentication for root?"; then
        info "Cancelled."; pause; return 0
    fi
    # Abort, not cancel: an unconfirmed guided-setup run gets the policy it
    # replaced put back, exactly as its timer would have done.
    _ssh_autorevert_abort || true
    if _ssh_revert_hardening; then
        success "Password authentication RE-ENABLED (toolkit hardening removed)."
        info "Distro defaults now apply. Your installed keys still work too."
        # The whole drop-in went, so PermitRootLogin/AllowUsers are back to the
        # distro default too — but the POLICY file survives and option 4 would
        # re-apply it. Say so: a silent re-lock is the surprise here.
        if [[ "$(_ssh_policy_get ROOT_LOGIN || echo prohibit-password)" == "no" ]]; then
            echo ""
            warn "Direct root SSH is available again — but the stored policy still says"
            warn "ROOT_LOGIN=no, ADMIN_USER=$(_ssh_policy_get ADMIN_USER || echo '(none)')."
            warn "Option 4 (or the wizard) would re-apply it."
            if confirm "Forget the stored policy, so future hardening only turns passwords off?"; then
                rm -f "$POLICY_CONF" && success "Policy cleared."
            else
                info "Policy kept."
            fi
        fi
    else
        error "Revert ran into a problem — check $SSHD_CONFIG and run 'sshd -t' manually."
    fi
    pause
}

# =============================================================================
# Status & audit
# =============================================================================
ssh_status() {
    clear
    echo -e "${BOLD}${CYAN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
    echo -e "${BOLD}${CYAN}  SSH status & audit${RESET}"
    echo -e "${BOLD}${CYAN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${RESET}"
    echo ""

    local port pw pubkey rootlogin
    port="$(_ssh_port)"
    pw="$(_ssh_effective passwordauthentication)"
    pubkey="$(_ssh_effective pubkeyauthentication)"
    rootlogin="$(_ssh_effective permitrootlogin)"

    printf "  ${BOLD}%-26s${RESET} %s\n" "SSH port:" "$port"
    printf "  ${BOLD}%-26s${RESET} %s\n" "PubkeyAuthentication:" "${pubkey:-unknown}"

    local pw_col="$pw"
    [[ "$pw" == "no"  ]] && pw_col="${GREEN}no  (key-only)${RESET}"
    [[ "$pw" == "yes" ]] && pw_col="${YELLOW}yes (passwords allowed)${RESET}"
    printf "  ${BOLD}%-26s${RESET} %b\n" "PasswordAuthentication:" "${pw_col:-unknown}"

    local rl_col="$rootlogin"
    [[ "$rootlogin" == "yes" ]] && rl_col="${YELLOW}yes${RESET}"
    [[ "$rootlogin" == "prohibit-password" ]] && rl_col="${GREEN}prohibit-password${RESET}"
    [[ "$rootlogin" == "no" ]] && rl_col="${RED}no (root SSH blocked)${RESET}"
    printf "  ${BOLD}%-26s${RESET} %b\n" "PermitRootLogin:" "${rl_col:-unknown}"

    local kcount=0
    [[ -s "$AUTH_KEYS" ]] && kcount="$(grep -cvE '^[[:space:]]*($|#)' "$AUTH_KEYS" 2>/dev/null || echo 0)"
    printf "  ${BOLD}%-26s${RESET} %s\n" "Authorized keys (root):" "$kcount"
    printf "  ${BOLD}%-26s${RESET} %s\n" "AllowUsers (effective):" "$(_ssh_effective_all allowusers || true)"

    # Admin accounts from the guided setup: key count + whether sudo really
    # grants root (asked of sudo itself, not guessed from group membership).
    local pol_users pu ph pk sudo_txt
    if pol_users="$(_ssh_policy_get ADMIN_USER)"; then
        for pu in $pol_users; do
            pk=0
            if ph="$(_ssh_user_home "$pu" 2>/dev/null)"; then
                if [[ -s "$ph/.ssh/authorized_keys" ]]; then
                    pk="$(grep -cvE '^[[:space:]]*($|#)' "$ph/.ssh/authorized_keys" 2>/dev/null || echo 0)"
                fi
            fi
            if _wz_sudo_ok "$pu"; then sudo_txt="${GREEN}sudo→root OK${RESET}"
            else sudo_txt="${RED}NO sudo→root${RESET}"; fi
            printf "  ${BOLD}%-26s${RESET} %b\n" "Admin user '$pu':" "$pk key(s), $sudo_txt"
        done
    fi

    if _ssh_dropin_supported; then
        printf "  ${BOLD}%-26s${RESET} %s\n" "Config method:" "drop-in ($DROPIN_DIR)"
    else
        printf "  ${BOLD}%-26s${RESET} %s\n" "Config method:" "managed block in $SSHD_CONFIG"
    fi

    # Duplicate definitions are the trap that makes a written directive silently
    # not apply, so name them here too — this screen is the "check your work" step.
    local dup_kw dup_n dup_txt=""
    for dup_kw in PasswordAuthentication PermitRootLogin; do
        dup_n="$(_ssh_keyword_sites "$dup_kw" | wc -l | tr -d ' ')"
        [[ "${dup_n:-0}" -gt 1 ]] && dup_txt+="$dup_kw ($dup_n files) "
    done
    if [[ -n "$dup_txt" ]]; then
        printf "  ${BOLD}%-26s${RESET} %b\n" "Duplicate directives:" "${YELLOW}${dup_txt}${RESET}"
        echo -e "  ${DIM}   sshd keeps the FIRST it reads — run option 4 or the wizard to see${RESET}"
        echo -e "  ${DIM}   which file wins and comment the loser out.${RESET}"
    fi

    if _ssh_autorevert_active; then
        local dl left=""
        dl="$(_ssh_autorevert_state_get DEADLINE || true)"
        if [[ "$dl" =~ ^[0-9]+$ ]]; then
            left=" (~$(( (dl - $(date +%s) + 59) / 60 )) min left)"
        fi
        printf "  ${BOLD}%-26s${RESET} %b\n" "Safety timer:" "${YELLOW}ARMED${left} — passwords will auto-restore; commit with option 5${RESET}"
        if _ssh_autorevert_boot_guarded; then
            printf "  ${BOLD}%-26s${RESET} %s\n" "" "a reboot before commit also undoes it"
        else
            printf "  ${BOLD}%-26s${RESET} %b\n" "" "${YELLOW}no boot guard — a reboot would leave the change in place${RESET}"
        fi
    elif _ssh_autorevert_pending; then
        if _ssh_autorevert_boot_guarded; then
            printf "  ${BOLD}%-26s${RESET} %b\n" "Safety timer:" "${YELLOW}UNCONFIRMED — countdown gone; undone at next boot unless you commit (option 5)${RESET}"
        else
            printf "  ${BOLD}%-26s${RESET} %b\n" "Safety timer:" "${YELLOW}UNCONFIRMED — countdown gone and nothing will undo it; commit (5) or roll back (6)${RESET}"
        fi
    else
        printf "  ${BOLD}%-26s${RESET} %s\n" "Safety timer:" "none"
    fi

    # ── Firewall view for the SSH port ─────────────────────────────────────────
    echo ""
    echo -e "${BOLD}Firewall (SSH port $port):${RESET}"
    if command -v ufw &>/dev/null; then
        local ufw_stat; ufw_stat="$(ufw status 2>/dev/null | head -1 || echo unknown)"
        echo -e "  UFW: $ufw_stat"
        ufw status 2>/dev/null | grep -E "(^|[[:space:]])$port(/tcp)?[[:space:]]" \
            | sed 's/^/    /' || echo -e "    ${DIM}no explicit rule for port $port${RESET}"
    elif command -v iptables &>/dev/null; then
        iptables -L INPUT -n 2>/dev/null | grep -E "dpt:$port(\b|$)" \
            | sed 's/^/    /' || echo -e "    ${DIM}no iptables rule referencing port $port${RESET}"
    else
        echo -e "    ${DIM}neither ufw nor iptables found${RESET}"
    fi

    echo ""
    echo -e "  ${DIM}Recommendation: add a key (option 1), run Verify (option 3) until it${RESET}"
    echo -e "  ${DIM}reads READY, then disable passwords (option 4) with the safety timer.${RESET}"
    pause
}

